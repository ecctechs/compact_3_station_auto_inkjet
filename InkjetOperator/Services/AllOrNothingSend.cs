namespace InkjetOperator.Services;

/// <summary>
/// โหมด "ส่งไม่ครบ ไม่ส่งเลย" — เปิด/ปิดในหน้า Setting → Station Options (โหมด Dev)
/// <para>
/// งานที่ใช้หลายเครื่อง (MK1 + MK2, UV1 + UV2, MK + UV2) ถ้าเครื่องไหนส่งไม่ผ่าน
/// ไม่ว่าจะต่อไม่ติดหรือส่งไปแล้วไม่ได้คำตอบ ระบบล้างคิวของงานนั้นทิ้งทั้งหมด
/// ตั้งงานกลับเป็นรอเริ่ม แล้วบอกชื่อเครื่องที่ต้องไปตรวจ พนักงานแก้เครื่องแล้วกดเริ่มงานใหม่
/// </para>
/// <para>
/// ไม่มีสถานะ "รอตรวจผล" ที่ทำให้คิวค้างอีก ผลไม่แน่นอนนับเป็นไม่ผ่าน และคิวที่ค้างจาก
/// ก่อนเปิดโหมดนี้ปลดได้ด้วยปุ่มหน้าเครื่อง หรือปุ่มยกเลิก / จบงาน ที่มีอยู่แล้ว
/// </para>
/// <para>
/// ข้อแลก: เครื่องที่รับงานไปก่อนอีกเครื่องจะล้ม ได้ข้อมูลไปแล้วจริง (ย้อนจากเครื่องไม่ได้)
/// ข้อความเตือนจะบอกชื่อเครื่องนั้นไว้ด้วย
/// </para>
/// <para>
/// ค่าอยู่ใน Setting.config ของแต่ละเครื่อง ตัวที่มีผลกับการส่งคือเครื่อง ST1
/// (ST1 เป็นคนส่งเข้าเครื่องทุกงาน รวมงานที่กดจาก ST3)
/// </para>
/// </summary>
public static class AllOrNothingSend
{
    /// <summary>คีย์ใน Setting.config — "1" = เปิด</summary>
    public const string Key = "SEND_ALL_OR_NOTHING";

    public static bool Enabled => CustomSettingsManager.Read(Key, "0").Trim() == "1";
}
