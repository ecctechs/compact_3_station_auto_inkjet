def annotate(file, spans, specific, common=None):
    p = ROOT / file
    original = p.read_bytes()
    text = original.decode('utf-8-sig')
    lines = text.splitlines(keepends=True)
    rules = dict(common or {})
    rules.update(specific)
    method = ''
    for i, line in enumerate(lines):
        if not any(a <= i + 1 <= b for a, b in spans):
            continue
        end = '\r\n' if line.endswith('\r\n') else '\n' if line.endswith('\n') else ''
        body = line[:-len(end)] if end else line
        prior = previous.get((file, i + 1))
        if prior:
            assert body == prior['before'] + ' // ' + prior['comment'], f'File changed: {file}:{i+1}'
            body = prior['before']
        key = body.strip()
        if re.match(r'(public|private|protected|static)\b', key):
            match = re.search(r'\b(\w+)\(', key)
            if match:
                method = match.group(1)
        if not key or key.startswith(('//', '/*', '*')) or key in ('{', '}', '};', '});', ');', '},', '],'):
            continue
        comment = rules.get(key)
        comment = exit_comments.get(Path(file).name, {}).get(i + 1, comment)
        action = purpose.get(method)
        if action:
            if key == 'try':
                comment = 'เริ่ม' + action + ' และดักข้อผิดพลาดไว้'
            elif key in ('catch', 'catch (Exception ex)'):
                comment = 'จัดการปัญหาระหว่าง' + action
        if key == 'finally' and method == 'BtnConfirm_Click':
            comment = 'ไม่ว่าสร้างงานได้หรือไม่ ต้องเปิดปุ่ม OK กลับมา'
        elif key == 'finally' and method == 'RefreshDataAsync':
            comment = 'จบรอบอ่านแล้ว ต้องเปิดให้รอบถัดไปทำงานได้'
        elif key == 'else' and file.endswith('ScanBarcodeUserControl.cs'):
            comment = 'Lot นี้ไม่มีแผนงานจากฐานข้อมูลต้นทาง'
        if comment is None:
            missing.append({'file': file, 'line': i + 1, 'code': key})
            continue
        if not comment:  # ข้อความหลายบรรทัดใน SQL ไม่แทรกคอมเมนต์ลงในสตริง
            continue
        lines[i] = body + ' // ' + comment + end
        changes.append({'file': file, 'line': i + 1, 'before': body, 'comment': comment})
    result = ''.join(lines).encode('utf-8')
    if original.startswith(b'\xef\xbb\xbf'):
        result = b'\xef\xbb\xbf' + result
    p.write_bytes(result)

