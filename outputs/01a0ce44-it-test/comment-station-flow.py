from pathlib import Path
import json

root=Path(__file__).resolve().parents[2]
manifest=Path(__file__).with_name('station-comment-changes.json')
changes=json.loads(manifest.read_text(encoding='utf-8')) if manifest.exists() else []
def annotate(file, entries):
    p=root/file
    before=p.read_bytes()
    lines=before.decode('utf-8-sig').splitlines(keepends=True)
    added=[]
    for item in entries.strip().splitlines():
        n, comment=item.split('|',1); n=int(n)
        old=lines[n-1]; ending='\r\n' if old.endswith('\r\n') else '\n'
        body=old.rstrip('\r\n')
        if body.endswith(' // '+comment): continue
        assert body.strip() and not body.lstrip().startswith('//'), (file,n)
        assert ' // ' not in body, (file,n,'existing comment')
        new=body+' // '+comment+ending
        lines[n-1]=new
        change=dict(file=file,line=n,old=old,new=new)
        changes.append(change);added.append(change)
    after=('\ufeff' if before.startswith(b'\xef\xbb\xbf') else '')+''.join(lines)
    p.write_bytes(after.encode('utf-8'))
    restored=after
    for c in reversed(added):
        parts=restored.splitlines(keepends=True)
        assert parts[c['line']-1]==c['new']
        parts[c['line']-1]=c['old'];restored=''.join(parts)
    assert restored.encode('utf-8')==before, file

